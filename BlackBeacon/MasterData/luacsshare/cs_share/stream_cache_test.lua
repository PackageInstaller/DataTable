local StreamCache = require("cs_share.stream_cache")
local cache = StreamCache:new(3)
cache:insert("aaaa")
cache:insert("bbbb")
cache:insert("cvvv")
cache:insert("eddd")
assert(12 == cache:cache_bytes())
assert(cache:get(6) == "vveddd", cache:get(6))
assert(cache:get(9) == "bcvvveddd", cache:get(9))
