local C = {
  Id2Name = {}
}

local function def_enum_from_tbl(typename, descname, tbl)
  local enum_members = {}
  for i = 1, #tbl do
    local name = tbl[i]
    assert(not C[name], name)
    C[name] = i
    enum_members[i] = i
    C.Id2Name[i] = name
  end
  C[typename] = enum_members
  C[descname] = tbl
end

function C.get_type_name(type)
  for name, idx in pairs(C) do
    if idx == type then
      return name
    end
  end
end

