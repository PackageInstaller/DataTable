	private void GenerateKeyExpansion(byte[] rgbKey)
	{
		switch ((m_blockSizeBits > rgbKey.Length * 8) ? m_blockSizeBits : (rgbKey.Length * 8))
		{
		case 128:
			m_Nr = 10;
			break;
		case 192:
			m_Nr = 12;
			break;
		case 256:
			m_Nr = 14;
			break;
		default:
			throw new CryptographicException(Environment.GetResourceString("Specified key is not a valid size for this algorithm."));
		}
		m_encryptKeyExpansion = new int[m_Nb * (m_Nr + 1)];
		m_decryptKeyExpansion = new int[m_Nb * (m_Nr + 1)];
		int num = 0;
		for (int i = 0; i < m_Nk; i++)
		{
			int num2 = rgbKey[num++];
			int num3 = rgbKey[num++];
			int num4 = rgbKey[num++];
			int num5 = rgbKey[num++];
			m_encryptKeyExpansion[i] = (num5 << 24) | (num4 << 16) | (num3 << 8) | num2;
		}
		if (m_Nk <= 6)
		{
			for (int j = m_Nk; j < m_Nb * (m_Nr + 1); j++)
			{
				int num6 = m_encryptKeyExpansion[j - 1];
				if (j % m_Nk == 0)
				{
					num6 = SubWord(rot3(num6));
					num6 ^= s_Rcon[j / m_Nk - 1];
				}
				m_encryptKeyExpansion[j] = m_encryptKeyExpansion[j - m_Nk] ^ num6;
			}
		}
		else
		{
			for (int k = m_Nk; k < m_Nb * (m_Nr + 1); k++)
			{
				int num6 = m_encryptKeyExpansion[k - 1];
				if (k % m_Nk == 0)
				{
					num6 = SubWord(rot3(num6));
					num6 ^= s_Rcon[k / m_Nk - 1];
				}
				else if (k % m_Nk == 4)
				{
					num6 = SubWord(num6);
				}
				m_encryptKeyExpansion[k] = m_encryptKeyExpansion[k - m_Nk] ^ num6;
			}
		}
		for (int l = 0; l < m_Nb; l++)
		{
			m_decryptKeyExpansion[l] = m_encryptKeyExpansion[l];
			m_decryptKeyExpansion[m_Nb * m_Nr + l] = m_encryptKeyExpansion[m_Nb * m_Nr + l];
		}
		for (int m = m_Nb; m < m_Nb * m_Nr; m++)
		{
			int num7 = m_encryptKeyExpansion[m];
			int num8 = MulX(num7);
			int num9 = MulX(num8);
			int num10 = MulX(num9);
			int num11 = num7 ^ num10;
			m_decryptKeyExpansion[m] = num8 ^ num9 ^ num10 ^ rot3(num8 ^ num11) ^ rot2(num9 ^ num11) ^ rot1(num11);
		}
	}

	private static int rot1(int val)
	{
		return ((val << 8) & -256) | ((val >> 24) & 0xFF);
	}

	private static int rot2(int val)
	{
		return ((val << 16) & -65536) | ((val >> 16) & 0xFFFF);
	}

	private static int rot3(int val)
	{
		return ((val << 24) & -16777216) | ((val >> 8) & 0xFFFFFF);
	}

	private static int SubWord(int a)
	{
		return s_Sbox[a & 0xFF] | (s_Sbox[(a >> 8) & 0xFF] << 8) | (s_Sbox[(a >> 16) & 0xFF] << 16) | (s_Sbox[(a >> 24) & 0xFF] << 24);
	}

	private static int MulX(int x)
	{
		int num = x & -2139062144;
		return ((x & 0x7F7F7F7F) << 1) ^ ((num - ((num >> 7) & 0x1FFFFFF)) & 0x1B1B1B1B);
	}
