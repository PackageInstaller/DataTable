local settingData = require("ClientData/ResUIData")
local ResUIBGM = require("ClientData/ResUIBGM")
local ResClientVersionFlag = require("ClientData/ResClientVersionFlag")

for _resUIID = 3901, 3999 do
	if settingData[_resUIID] then
		local uiResInfo = settingData[_resUIID]
		local uiKey = "getLightBlackHeroDlg_" .. string.sub(uiResInfo.prefabKey, 24, -1)
		local uiKey1 = "getUpLightBlackHeroDlg_" .. string.sub(uiResInfo.prefabKey, 24, -1)

		UIMap[uiKey] = {
			pathLua = "UI/Hero/GetLightBlackHeroDlg",
			resUIID = _resUIID
		}
		UIMap[uiKey1] = {
			pathLua = "UI/Hero/GetUpLightBlackHeroDlg",
			resUIID = _resUIID
		}
	else
		break
	end
end

local replaceUIDic = {}

for _, config in pairs(ResClientVersionFlag) do
	if config.flag == 1 and config.ui_id and config.ui_prefab then
		replaceUIDic[config.ui_id] = config.ui_prefab
	end
end

for name, info in pairs(UIMap) do
	local uiId = info.resUIID
	local uiData = settingData[uiId]

	if uiData then
		for key, value in pairs(uiData) do
			info[key] = value
		end
	end

	if ResUIBGM[uiId] then
		info.bgm = ResUIBGM[uiId].bgm
	end

	if replaceUIDic[uiId] then
		info.prefab = replaceUIDic[uiId]
	end
end

return UIMap
