	StoryName/StoryNameInputField
--]]
	local tmp = Root:Find("StoryName/StoryNameInputField").gameObject
	if tolua.getpeer(tmp) == nil then
		tolua.setpeer(tmp, {})
	end
	self.storyNameInputField = tmp

	tmp.inputField = tmp:GetComponent(TypeInfo.InputField)
	tmp.inputField.onEndEdit:RemoveAllListeners()
	tmp.inputField.onEndEdit:AddListener(function (content)
			if self.storyNameInputField_InputField_onEndEdit then
				self:storyNameInputField_InputField_onEndEdit(self.storyNameInputField,content)
			end
		end)
	tmp.inputField.onValueChanged:RemoveAllListeners()
	tmp.inputField.onValueChanged:AddListener(function (content)
			if self.storyNameInputField_InputField_onValueChanged then
				self:storyNameInputField_InputField_onValueChanged(self.storyNameInputField,content)
			end
		end)


end

