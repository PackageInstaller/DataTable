		{
			1 => GuideType.HandBookDailyTab, 
			2 => GuideType.HandBookTargetTab, 
			3 => GuideType.HandBookRaidTab, 
			4 => GuideType.HandBookTrainingTab, 
			5 => GuideType.HandBookPowerExchangeTab, 
