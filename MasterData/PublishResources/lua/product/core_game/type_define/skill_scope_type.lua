  return scopeType == SkillScopeType.EmptyRandGrid or scopeType == SkillScopeType.RandomRectAndCount or scopeType == SkillScopeType.RandomGrids or scopeType == SkillScopeType.MultiRandomRange or scopeType == SkillScopeType.RandomPosEmptyOrTrap or scopeType == SkillScopeType.QierMonsterRoundRandom or scopeType == SkillScopeType.RandomGridsByPieceType or scopeType == SkillScopeType.RandomGridsInRangeByPieceType
end

