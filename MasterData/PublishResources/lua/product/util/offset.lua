function CalcXAddYOffset(n)
  local offset = {}
  for y = 0, n do
    local x = n - math.abs(y)
    offset[#offset + 1] = {x, y}
    offset[#offset + 1] = {
      x,
      -y
    }
    offset[#offset + 1] = {
      -x,
      y
    }
    offset[#offset + 1] = {
      -x,
      -y
    }
  end
  return offset
end

