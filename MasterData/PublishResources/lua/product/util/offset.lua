function CalcRing(n)
  local offset = {}
  
  for i = -n, n do
    for j = -n, n do
      if i > -n and i < n and j > -n and j < n then
      else
        offset[#offset + 1] = {i, j}
      end
    end
  end
  return offset
end

function CalcAllRing(n)
  local ret = {}
  for i = 1, n do
    local offset = CalcRing(i)
    for _, v in ipairs(offset) do
      ret[#ret + 1] = v
    end
  end
  return ret
end

