function AudioHelperController.PlayInnerGameVoiceByAudioId(audioID, isLoop, scaler, mixPath)
  if USEADX2AUDIO then
    local l_strAcbName, l_strCueName = AudioHelperController.GetCueSheetAndCue(audioID)
    if l_strAcbName == nil then
      Log.error("adx2 PlayInnerGameVoiceByAudioId not find cfg audioid:", audioID)
      return -1
    end
    local playingID = CriAudioManager.Instance:PlayCueInnerCriVoice(l_strAcbName, l_strCueName, isLoop or false, scaler or 1)
    if playingID == -1 then
      AudioHelperController.RequestInnerGameVoiceByResName(l_strAcbName)
      playingID = CriAudioManager.Instance:PlayUIVoiceCue(l_strAcbName, l_strCueName, true)
    end
    return playingID
  else
    local l_resname = AudioHelper.GetAudioResName(audioID)
    return AudioManager.Instance:PlayInnerGameVoice(l_resname, isLoop or false, scaler or 1, mixPath or "")
  end
end

