function AudioHelperController.RequestUIVoiceList(audioIDList)
  local res_table = {}
  for index, value in ipairs(audioIDList) do
    local l_res
    if USEADX2AUDIO then
      local l_strAcbName, l_strCueName = AudioHelperController.GetCueSheetAndCue(value)
      l_res = l_strAcbName
    else
      l_res = AudioHelper.GetConfigName(value)
    end
    if l_res and l_res ~= "" and not res_table[l_res] then
      AudioHelperController.RequestUIVoiceByResName(l_res)
      res_table[l_res] = true
    end
  end
end

