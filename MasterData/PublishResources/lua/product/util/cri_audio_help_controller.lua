function AudioHelperController.GetCueSheetAndCue(res_id)
  if USEADX2AUDIO then
    local l_cfg_adx2_audio = Cfg.cfg_adx2_audio[res_id]
    if l_cfg_adx2_audio == nil then
      Log.error("audioid: ", res_id, "not find res")
      return nil, nil
    end
    local l_cuesheet_id = l_cfg_adx2_audio.CueSheetID
    local l_cfg_cuesheet = Cfg.cfg_cuesheet[l_cuesheet_id]
    if l_cfg_cuesheet == nil then
      Log.error("cuesheet_id: ", l_cuesheet_id, "not find audioid:", res_id)
      return nil, nil
    end
    local l_strAcbName = l_cfg_cuesheet.AcbFileName
    local l_strCueName = l_cfg_adx2_audio.CueName
    return l_strAcbName, l_strCueName
  end
  Log.error("audioid: ", res_id, "not find res")
  return nil, nil
end

