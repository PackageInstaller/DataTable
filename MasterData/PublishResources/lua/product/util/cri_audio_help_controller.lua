function AudioHelperController.SetInnerVolumeRuntime(player_id, volume)
  local BindingFlags = System.Reflection.BindingFlags
  local flag = System.Reflection.BindingFlags.GetMask(BindingFlags.Public, BindingFlags.NonPublic, BindingFlags.Static, BindingFlags.Instance)
  require("tolua.reflection")
  tolua.loadassembly("Assembly-CSharp")
  local type1 = typeof("CriAudioManager")
  local cri_instance = CriAudioManager.Instance
  local playerlist_field = tolua.getfield(type1, "m_ActiveInnerCriPlayer", flag)
  if not playerlist_field then
    Log.fatal("get m_ActiveInnerCriPlayer field failed!")
    return
  end
  local player_lists = playerlist_field:Get(cri_instance)
  if not player_lists then
    Log.fatal("get m_ActiveInnerCriPlayer failed!")
    return
  end
  local player
  if player_lists:ContainsKey(player_id) then
    player = player_lists[player_id]
  end
  if not player then
    Log.info("m_ActiveInnerCriPlayer don't cantain key", player_id)
    return
  end
  local type2 = typeof("SimpleCriPlayer")
  local Volume = tolua.getproperty(type2, "Volume")
  if not Volume then
    Log.fatal("get ", player_id, " Volume faild!")
    return
  end
  Volume:Set(player, volume, nil)
end

