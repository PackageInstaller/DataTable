    local l_strAcbName, l_strCueName = AudioHelperController.GetCueSheetAndCue(audioID)
    if l_strAcbName == nil or l_strCueName == nil then
      Log.error("AudioHelperController.PlayInnerGameSfx not find cfg audioid:", audioID)
      return -1
    end
    if isLoop ~= nil then
      return CriAudioManager.Instance:PlayInnerCue(l_strAcbName, l_strCueName, isLoop)
    else
      return CriAudioManager.Instance:PlayInnerCue(l_strAcbName, l_strCueName)
    end
  else
    local soundResName = AudioHelper.GetAudioResName(audioID)
    if isLoop ~= nil then
      return AudioManager.Instance:PlayInnerGameSfx(soundResName, isLoop)
    else
      return AudioManager.Instance:PlayInnerGameSfx(soundResName)
    end
  end
  return -1
end

