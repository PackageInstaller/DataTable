function AudioHelperController.PlayAdx2UISound(audioID)
  if not audioID then
    Log.fatal("attempt to play UIVoice with nil AudioID")
    return -1
  end
  local l_cfg_adx2_audio = Cfg.cfg_adx2_audio[audioID]
  if not l_cfg_adx2_audio then
    Log.fatal("can not find adx2 audio source by ID: " .. tostring(audioID))
    return -1
  end
  local l_cuesheet_id = l_cfg_adx2_audio.CueSheetID
  local l_cfg_cuesheet = Cfg.cfg_cuesheet[l_cuesheet_id]
  if not l_cfg_cuesheet then
    Log.fatal("can not find adx2 cuesheet source by ID: " .. tostring(l_cuesheet_id))
    return -1
  end
  local l_strAcbName = l_cfg_cuesheet.AcbFileName
  local l_strCueName = l_cfg_adx2_audio.CueName
  return CriAudioManager.Instance:PlayUIAcbCueDontRelease(l_strAcbName, l_strCueName)
end
