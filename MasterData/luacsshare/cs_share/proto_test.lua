local Proto = require("cs_share.proto")
print("---proto test begin---")
local cache = Proto.new_proto_cache(3)
cache:push_send_pkg("aaaaa")
cache:push_send_pkg("bbbbbb")
cache:push_send_pkg("cccccc")
cache:push_send_pkg("dddddd")
assert(4 == cache:get_send_num())
local c = cache:peek_cache()
assert(3 == #c and "dddddd" == c[1] and "bbbbbb" == c[3])
assert(not cache:peer_recv_ack(5))
assert(cache:peer_recv_ack(3))
c = cache:peek_cache()
assert(1 == #c and "dddddd" == c[1])
cache:push_send_pkg("eeeeee")
cache:push_send_pkg("ffffff")
assert(6 == cache:get_send_num())
assert(3 == cache:get_cache_size())
local ok, c = cache:peek_unack_pkgs(4)
assert(ok and 2 == #c and "ffffff" == c[1] and "eeeeee" == c[2])
ok, c = cache:peek_unack_pkgs(5)
assert(ok and 1 == #c and "ffffff" == c[1])
assert(3 == cache:get_cache_size())
assert(cache:peer_recv_ack(5))
assert(1 == cache:get_cache_size())
print("---proto test end---")
