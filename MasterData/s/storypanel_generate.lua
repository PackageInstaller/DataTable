function StoryPanel:InitGenerate__1(Root, data)
--[[
	DoNextBtn
--]]
	local tmp = Root:Find("DoNextBtn").gameObject
	if tolua.getpeer(tmp) == nil then
		tolua.setpeer(tmp, {})
	end
	self.doNextBtn = tmp

	tmp.button = tmp:GetComponent(TypeInfo.Button)
	tmp.button.onClick:RemoveAllListeners()
	tmp.button.onClick:AddListener(function ()
		UIMgr:SendUiUseMessage("StoryPanel_doNextBtn")
			if self.doNextBtn_Button_onClick then
				self:doNextBtn_Button_onClick(self.doNextBtn)
			end
		end)

	tmp.image = tmp:GetComponent(TypeInfo.Image)


end

