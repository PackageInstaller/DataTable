  factoryNode:AddChild(RedDotStaticTypeId.FactoryEnerage)
  factoryNode:AddChild(RedDotStaticTypeId.FactoryProcessLine)
  local mainSideNode = mainNode:AddChild(RedDotStaticTypeId.MainSide)
