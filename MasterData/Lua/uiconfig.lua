function UIConfig.CheckUISKin(vmName)
    if IsNull(ConfigMgr.Config.UIskinMap) then
        return UIConfig[vmName];
    end
    if IsNull(DataMgr.Player.uiSkin) or IsNullOrEmpty(DataMgr.Player.uiSkin.use) then
        return UIConfig[vmName];
    end
    local curSkin = ConfigMgr.Config.UIskinMap[DataMgr.Player.uiSkin.use];
    if curSkin == nil then
        return UIConfig[vmName];
    end
    return curSkin.PanelName;
end


function UIConfig.CheckUIFriendChatSKin(vmName)
    if IsNull(ConfigMgr.Config.FriendChatSkinMap) then
        return UIConfig[vmName];
    end
    if IsNull(DataMgr.Player.Friends) or IsNullOrEmpty(DataMgr.Player.Friends.ChatSkinId) then
        return UIConfig[vmName];
    end
    local curSkin = ConfigMgr.Config.FriendChatSkinMap[DataMgr.Player.Friends.ChatSkinId];
    if curSkin == nil then
        return UIConfig[vmName];
    end
    return curSkin.ChatSkinPath;
end

function UIConfig.Clear()
    LuaMgr.ClearVM(UIName.FriendChatViewModel)
    LuaMgr.ClearVM(UIName.MainPageViewModel)
end

function UIConfig.GetPrefabPath(vmName)
    if vmName == UIName.MainPageViewModel then
        return UIConfig.CheckUISKin(vmName);
    elseif vmName == UIName.FriendChatViewModel then
        return UIConfig.CheckUIFriendChatSKin(vmName);
    end
    return UIConfig[vmName];
end