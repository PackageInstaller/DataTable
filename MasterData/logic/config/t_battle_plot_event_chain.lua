local mt = {
	__index = function(t, key)
		local index = title[key]

		if index then
			return rawget(t, index)
		else
			error(string.format("the field name [%s] is nonexist!", key))
		end
	end
}

for i, v in ipairs(dataList) do
	local parent1 = t_battle_plot_event_chain[v[1]]

	if parent1 == nil then
		parent1 = {}
		t_battle_plot_event_chain[v[1]] = parent1
	end

	parent1[v[2]] = v

	setmetatable(v, mt)
end

