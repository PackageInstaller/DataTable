	shrinkVertical = function(self, arg_6_1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 1, 0.1), cc.CallFunc:create(arg_6_1)))
	end,
	shrinkHorizon = function(self, arg_8_1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 0.1, 1), cc.CallFunc:create(arg_8_1)))
	end,
	shrinkBoth = function(self, arg_10_1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 0.1), cc.CallFunc:create(arg_10_1)))
	end,
	moveFadeOut = function(self, arg_13_1)
		self.rootpanel:runAction(cc.Sequence:create(cc.Spawn:create(cc.MoveBy:create(0.1, cc.p(0, -200)), cc.FadeOut:create(0.1)), cc.CallFunc:create(function(...)
			if arg_13_1 then
				arg_13_1()
			end
		end)))
	end
}

