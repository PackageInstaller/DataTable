PopBaseLayer.showActions = {
	fadeIn = function(self)
		self.rootpanel:setCascadeOpacityEnabled(true)
		self.rootpanel:setOpacity(0)
		self.rootpanel:runAction(cc.FadeIn:create(0.2))
	end,
	extendVertical = function(self)
		self.rootpanel:setScaleY(0.1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 1, 1.1), cc.ScaleTo:create(0.1, 1, 1)))
	end,
	extendHorizon = function(self)
		self.rootpanel:setScaleX(0.1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 1.1, 1), cc.ScaleTo:create(0.1, 1, 1)))
	end,
	extendBoth = function(self)
		self.rootpanel:setScale(0.1)
		self.rootpanel:runAction(cc.Sequence:create(cc.ScaleTo:create(0.2, 1.1), cc.ScaleTo:create(0.1, 1)))
	end,
	moveFadeIn = function(self, arg_11_1)
		self.rootpanel:setOpacity(0)
		self.rootpanel:setPositionY(self:getPositionY() - 200)
		self.rootpanel:runAction(cc.Sequence:create(cc.Spawn:create(cc.MoveBy:create(0.1, cc.p(0, 200)), cc.FadeIn:create(0.1)), cc.CallFunc:create(function(...)
			if arg_11_1 then
				arg_11_1()
			end
		end)))
	end
}
PopBaseLayer.hideActions = {
