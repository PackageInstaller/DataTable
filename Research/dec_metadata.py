def apply_chunk(chunk, key, ops):
    b = bytearray(chunk)
    n = len(b)
    if n == 0:
        return bytes(b)

    v5 = u32(0x66876718) % n

    for c in ops:
        if c in A:
            idx_const, k, xc = A[c]
            idx = u32(idx_const) % n
            b[idx] = (b[idx] ^ key[k] ^ xc) & 0xFF

        elif c in C:
            idx_const, k, xc = C[c]
            idx = u32(idx_const) % n
            b[idx] = (b[idx] ^ key[k] ^ xc) & 0xFF

        elif c in B:
            idx_const, k, delta = B[c]
            idx = u32(idx_const) % n
            b[idx] = (b[idx] + delta - key[k]) & 0xFF

        elif c in R266:
            k, const = R266[c]
            idx = u32(const) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 + 4) & 7)) | (v33 << ((4 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R253:
            k, const = R253[c]
            idx = u32(const) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 - 1) & 7)) | (v33 << ((1 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R269:
            k, const = R269[c]
            idx = u32(const) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 + 6) & 7)) | (v33 << ((2 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R263:
            k, const = R263[c]
            idx = u32(const) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 + 2) & 7)) | (v33 << ((6 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R206:
            k, const = R206[c]
            idx = u32(const) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 + 3) & 7)) | (v33 << ((5 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R217:
            if c == 0x61:
                typ, k, val = R217[c]
                v24 = u32(val)
                v32 = v24 // n
            else:
                typ, k, val, extra = R217[c]
                v24 = u32(val)
                v32 = u32(extra) // n
            idx = (v24 - v32 * n) % n
            v33 = b[idx]
            v12 = key[k]
            v19 = (v33 >> ((v12 + 5) & 7)) | (v33 << ((3 - v12) & 7))
            b[idx] = v19 & 0xFF

        elif c in R230:
            k, const = R230[c]
            idx = u32(const) % n
            v36 = b[idx]
            v29 = key[k]
            v37 = (~v29) & 7
            v38 = v36 >> ((v29 + 1) & 7)
            b[idx] = (v38 | (v36 << v37)) & 0xFF

        elif c in R258:
            k, const = R258[c]
            idx = u32(const) % n
            v36 = b[idx]
            v26 = key[k]
            v37 = (-v26) & 7
            v38 = v36 >> (v26 & 7)
            b[idx] = (v38 | (v36 << v37)) & 0xFF

        elif c in E2:
            k, c17, c18 = E2[c]
            idx1 = u32(c17) % n
            idx2 = (key[k] + u32(c18)) % n
            v40 = (b[idx2] - 1) & 0xFF
            b[idx1] = (b[idx1] - v40) & 0xFF
            b[idx2] = v40

        elif c in SW:
            k, c21, c22 = SW[c]
            idx1 = u32(c21) % n
            idx2 = (key[k] + u32(c22)) % n
            b[idx1], b[idx2] = b[idx2], b[idx1]

        else:
            # default
            idx1 = v5
            idx2 = (key[123] + u32(241954386)) % n
            b[idx1], b[idx2] = b[idx2], b[idx1]

    return bytes(b)

def decrypt(inp, outp=None):
    data = open(inp, 'rb').read()

    magic = struct.unpack('<I', data[:4])[0]
    if magic != 0x1357FEDA:
        return

    body_len = struct.unpack('<I', data[4:8])[0]

    key = data[0x08:0x108]
    ops = data[0x108:0x148]
    body = data[0x148:]

    out = bytearray()

    pos = 0
    while pos < body_len:
        chunk = body[pos:pos + 0x40]
        out += apply_chunk(chunk, key, ops)
        pos += 0x40

    # "CODEPHIL"
    plain = bytes(out[8:])

    outp = inp

    with open(outp, 'wb') as f:
        f.write(plain)

    print(plain[:5].hex())

