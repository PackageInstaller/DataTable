def ror1(b, n):
    return ((b >> n) | (b << (8 - n))) & 0xFF


def u32(x):
    return x & 0xFFFFFFFF


def apply_block(buf, key, ops_raw):
    n = len(buf)
    for op_byte in ops_raw:
        spec = OP_SPECS[op_byte]
        kind = spec[0]
        if kind == "xor":
            _, pos_c, k, xv = spec
            buf[pos_c % n] ^= key[k] ^ xv
        elif kind == "ror":
            _, pos_c, k, c = spec
            buf[pos_c % n] = ror1(buf[pos_c % n], (key[k] + c) & 7)
        elif kind == "swap":
            _, pos_c, k, c = spec
            a = pos_c % n
            b = u32(key[k] + c) % n
            buf[a], buf[b] = buf[b], buf[a]
        elif kind == "dec":
            _, c, k, pos_c = spec
            idx = u32(key[k] + c) % n
            pos = pos_c % n
            tmp = (buf[idx] - 1) & 0xFF
            buf[pos] = (buf[pos] - tmp) & 0xFF
            buf[idx] = tmp
        elif kind == "add":
            _, pos_c, c, k = spec
            buf[pos_c % n] = (buf[pos_c % n] + (c - key[k])) & 0xFF
        elif kind == "sub":
            _, pos_c, k = spec
            buf[pos_c % n] = (buf[pos_c % n] - key[k]) & 0xFF
        else:
            raise RuntimeError(f"不明op {spec}")


def decrypt(path):
    data = open(path, "rb").read()
    magic, v5 = struct.unpack_from("<II", data, 0)
    if magic != 0x1357FEDA:
        raise SystemExit(f"头错误{magic:#x}")
    if 0x148 + v5 != len(data):
        raise SystemExit(f"{v5}, {len(data) - 0x148}")
    key = data[0x08:0x108]
    ops_raw = data[0x108:0x148]
    enc = bytearray(data[0x148:0x148 + v5])
    for off in range(0, len(enc), 64):
        block = enc[off:off + 64]
        apply_block(block, key, ops_raw)
        enc[off:off + 64] = block
    dec = bytes(enc)
    if dec[:8] != b"CODEPHIL":
        raise SystemExit(f"解密后标记:{dec[:8]!r}")
    sanity, version = struct.unpack_from("<II", dec, 8)
    print(f"sanity=0x{sanity:08X} version={version}")
    return dec[8:]


